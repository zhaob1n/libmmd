static inline unsigned cp_width(uint32_t cp) {
    if (cp >= 32 && cp < 127) return ASCII_W[cp - 32];
    if (cp < 32) return 0;
    if (cp >= 0xA0 && cp <= 0xFF) return LAT1_W[cp - 0xA0];
    /* East Asian wide / fullwidth ranges */
    if ((cp >= 0x1100 && cp <= 0x115F) || (cp >= 0x2E80 && cp <= 0xA4CF) ||
        (cp >= 0xAC00 && cp <= 0xD7A3) || (cp >= 0xF900 && cp <= 0xFAFF) ||
        (cp >= 0xFE30 && cp <= 0xFE4F) || (cp >= 0xFF00 && cp <= 0xFF60) ||
        (cp >= 0xFFE0 && cp <= 0xFFE6) || (cp >= 0x1F300 && cp <= 0x1FAFF) ||
        (cp >= 0x20000 && cp <= 0x3FFFD))
        return 2048;
    if (cp >= 0x0300 && cp <= 0x036F) return 0; /* combining */
    return 1188;
}

/* Sum of advances plus kerning (1/2048 em), then Chromium's LayoutUnit snap: ceil to 1/64 px. */
double text_width(Str s, double fs) {
    int64_t acc = 0;
    const unsigned char *p = (const unsigned char *)s.p;
    size_t i = 0, n = s.n;
    uint32_t prev = 0;
    while (i < n) {
        unsigned c = p[i];
        uint32_t cp = c;
        size_t len = 1;
        if (c >= 0xF0 && i + 3 < n) { cp = ((c & 7u) << 18) | ((p[i + 1] & 63u) << 12) | ((p[i + 2] & 63u) << 6) | (p[i + 3] & 63u); len = 4; }
        else if (c >= 0xE0 && i + 2 < n) { cp = ((c & 15u) << 12) | ((p[i + 1] & 63u) << 6) | (p[i + 2] & 63u); len = 3; }
        else if (c >= 0xC0 && i + 1 < n) { cp = ((c & 31u) << 6) | (p[i + 1] & 63u); len = 2; }
        acc += cp_width(cp);
        if (cp >= 32 && cp < 127 && prev && KL[prev - 32]) acc += KT[KL[prev - 32] - 1][cp - 32];
        prev = cp >= 32 && cp < 127 ? cp : 0;
        i += len;
    }
    if (acc <= 0) return 0;
    return ceil((double)acc * fs * 64.0 / 2048.0 - 1e-9) / 64.0;
}

static bool is_br(Str s, size_t i, size_t *len) {
    /* <br>, <br/>, <br />, case-insensitive */
    if (i + 4 > s.n || s.p[i] != '<' || (s.p[i + 1] | 32) != 'b' || (s.p[i + 2] | 32) != 'r') return false;
    size_t j = i + 3;
    while (j < s.n && s.p[j] == ' ') j++;
    if (j < s.n && s.p[j] == '/') j++;
    if (j < s.n && s.p[j] == '>') { *len = j + 1 - i; return true; }
    return false;
}

Str label_normalize(Arena *a, Str raw, bool *ok) {
    *ok = true;
    Str s = str_trim(raw);
    bool md = false;
    if (s.n >= 2 && s.p[0] == '"' && s.p[s.n - 1] == '"') {
        s.p++, s.n -= 2;
        if (s.n >= 2 && s.p[0] == '`' && s.p[s.n - 1] == '`') { s.p++, s.n -= 2; md = true; }
    }
    bool need = false;
    for (size_t i = 0; i < s.n; i++) {
        char c = s.p[i];
        if (c == '<' || (md && (c == '*' || c == '_' || c == '\n'))) { need = true; break; }
    }
    if (!need) return s;
    char *o = arena_alloc(a, s.n + 1, 1);
    if (!o) { *ok = false; return (Str){}; }
    size_t k = 0;
    for (size_t i = 0; i < s.n; i++) {
        size_t bl = 0;
        char c = s.p[i];
        if (c == '<' && is_br(s, i, &bl)) { o[k++] = '\n'; i += bl - 1; continue; }
        if (md && (c == '*' || c == '_')) continue; /* basic markdown: drop emphasis markers */
        if (md && c == '\n') {
            while (k && o[k - 1] == ' ') k--;
            o[k++] = '\n';
            while (i + 1 < s.n && is_sp(s.p[i + 1])) i++;
            continue;
        }
        o[k++] = c;
    }
    o[k] = 0;
    return (Str){.p = o, .n = k};
}

bool label_next_line(Str s, size_t *pos, Str *line) {
    if (*pos > s.n) return false;
    const char *st = s.p + *pos;
    const char *nl = s.n > *pos ? memchr(st, '\n', s.n - *pos) : nullptr;
    size_t len = nl ? (size_t)(nl - st) : s.n - *pos;
    *line = (Str){.p = st, .n = len};
    *pos += len + 1;
    return true;
}

void label_measure(Str s, double fs, double *w, unsigned *lines) {
    double mw = 0;
    unsigned cnt = 0;
    size_t pos = 0;
    Str ln;
    if (s.n == 0) { *w = 0; *lines = 0; return; }
    while (label_next_line(s, &pos, &ln)) {
        double lw = text_width(ln, fs);
        if (lw > mw) mw = lw;
        cnt++;
    }
    *w = mw;
    *lines = cnt;
}

/* "Open Sans" (C4 labels) ASCII advances in 1/1000 em, measured in Chromium; kerning ignored.
 * Non-ASCII falls back to the default face's advance. */
static constexpr unsigned short OS_ADV[95] = {260,264,398,646,572,827,729,219,295,295,551,572,259,322,263,367,572,572,572,572,572,572,572,572,572,572,263,263,572,572,572,432,896,632,646,630,726,556,516,727,737,279,269,612,522,899,753,778,602,778,617,548,551,729,596,923,578,559,572,327,367,327,572,438,277,556,612,479,612,562,336,543,613,252,252,525,252,926,613,602,612,612,409,477,356,613,500,775,523,501,469,375,549,375,572};
double text_width_os(Str s, double fs) {
    double acc = 0;
    size_t i = 0;
    while (i < s.n) {
        unsigned char c = (unsigned char)s.p[i];
        if (c >= 32 && c < 127) { acc += OS_ADV[c - 32] * fs / 1000.0; i++; continue; }
        size_t j = i + 1;
        while (j < s.n && ((unsigned char)s.p[j] & 0xC0) == 0x80) j++;
        acc += text_width((Str){.p = s.p + i, .n = j - i}, fs);
        i = j;
    }
    return acc;
}

void label_measure_f(Str s, double fs, double (*meas)(Str, double), double *w, unsigned *lines) {
    size_t pos = 0;
    Str ln;
    double mw = 0;
    unsigned k = 0;
    if (s.n == 0) { *w = 0, *lines = 0; return; }
    while (label_next_line(s, &pos, &ln)) mw = fmax(mw, meas(ln, fs)), k++;
    *w = mw, *lines = k;
}
