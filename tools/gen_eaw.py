#!/usr/bin/env python3
"""Regenerate src/eaw_tbl.inc from Python's unicodedata (East_Asian_Width and Mn/Me)."""
import sys
import unicodedata as u
from pathlib import Path

def ranges_for(pred):
    rs, start, prev = [], None, None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            rs.append((start, prev))
            start = None
    if start is not None:
        rs.append((start, prev))
    return rs

def emit(name, rs, comment):
    lines = [f"/* {comment} */", f"static constexpr uint32_t {name}[][2] = {{"]
    row = "   "
    for s, e in rs:
        cell = f" {{{s:#x},{e:#x}}},"
        if len(row) + len(cell) > 116:
            lines.append(row)
            row = "   " + cell
        else:
            row += cell
    if row.strip():
        lines.append(row)
    lines.append("};")
    lines.append("")
    return "\n".join(lines)

def main():
    root = Path(__file__).resolve().parents[1]
    dest = root / "src" / "eaw_tbl.inc"
    wf = ranges_for(lambda cp: u.east_asian_width(chr(cp)) in ("W", "F"))
    mn = ranges_for(lambda cp: u.category(chr(cp)) in ("Mn", "Me"))
    text = (
        f"/* Generated by tools/gen_eaw.py from Python unicodedata {u.unidata_version}. Do not edit. */\n\n"
        + emit("EAW_WF", wf, "Unicode East_Asian_Width Wide and Fullwidth")
        + emit("COMB_MN", mn, "Unicode general category Mn (nonspacing) and Me (enclosing)")
    )
    dest.write_text(text)
    print(f"wrote {dest} ({len(wf)} W/F ranges, {len(mn)} Mn/Me ranges)", file=sys.stderr)

if __name__ == "__main__":
    main()
