/* gen_eaw: regenerate src/eaw_tbl.inc (East_Asian_Width Wide/Fullwidth, general category Mn/Me) from
 * the Unicode Character Database.
 * usage: build/gen_eaw EastAsianWidth.txt UnicodeData.txt
 * Wide is what EastAsianWidth.txt says, unassigned code points of its ranges included (the CJK
 * blocks are wide whether or not a character lives there yet). A mark is a code point UnicodeData.txt
 * lists as Mn or Me, its <..., First> and <..., Last> pairs expanded. */
#include "qa/qa.h"

enum { NCP = 0x110000 };
static bool wide[NCP], mark[NCP];

static void unicode_data(const char *path) {
    size_t len;
    char *s = qa_read(path, &len);
    unsigned first = 0;
    for (char *line = s, *end; *line; line = end + (*end == '\n')) {
        end = line + strcspn(line, "\n");
        if (end == line) continue;
        unsigned cp = (unsigned)strtoul(line, nullptr, 16);
        char *name = strchr(line, ';') + 1, *cat = strchr(name, ';') + 1;
        bool lo = memmem(name, (size_t)(cat - name), ", First>", 8), hi = memmem(name, (size_t)(cat - name), ", Last>", 7);
        if (lo) { first = cp; continue; }
        bool m = cat[0] == 'M' && (cat[1] == 'n' || cat[1] == 'e') && cat[2] == ';';
        for (unsigned c = hi ? first : cp; c <= cp; c++) mark[c] = m;
    }
}

/* returns the version from the first line */
static char *east_asian_width(const char *path) {
    size_t len;
    char *s = qa_read(path, &len);
    char *v = strstr(s, "EastAsianWidth-"), *ve;
    if (!v || !(ve = strstr(v, ".txt"))) qa_die("%s: no version on the first line", path);
    char *version = qa_fmt("%.*s", (int)(ve - v - 15), v + 15);
    for (char *line = s, *end; *line; line = end + (*end == '\n')) {
        end = line + strcspn(line, "\n");
        if (*line == '#' || end == line) continue;
        char *p;
        unsigned lo = (unsigned)strtoul(line, &p, 16), hi = lo;
        if (p[0] == '.' && p[1] == '.') hi = (unsigned)strtoul(p + 2, &p, 16);
        p += strspn(p, " ");
        if (*p++ != ';') qa_die("%s: bad line %.*s", path, (int)(end - line), line);
        p += strspn(p, " ");
        bool w = (p[0] == 'W' || p[0] == 'F') && (p[1] == ' ' || p[1] == '#' || p + 1 == end);
        for (unsigned c = lo; c <= hi; c++) wide[c] = w;
    }
    return version;
}

static void emit(qa_buf o[static 1], const char *name, const bool set[static NCP], const char *comment, size_t count[static 1]) {
    qa_putf(o, "/* %s */\nstatic constexpr uint32_t %s[][2] = {\n", comment, name);
    char row[256] = "   ";
    size_t rn = 3;
    for (unsigned cp = 0; cp < NCP; cp++) {
        if (!set[cp]) continue;
        unsigned e = cp;
        while (e + 1 < NCP && set[e + 1]) e++;
        char cell[64];
        int cn = snprintf(cell, sizeof cell, " {%#x,%#x},", cp, e);
        if (rn + (size_t)cn > 116) {
            qa_putf(o, "%s\n", row);
            rn = 3;
        }
        memcpy(row + rn, cell, (size_t)cn + 1);
        rn += (size_t)cn;
        ++*count;
        cp = e;
    }
    if (rn > 3) qa_putf(o, "%s\n", row);
    qa_puts(o, "};\n\n");
}

int main(int argc, char *argv[]) {
    qa_at_root(argc, argv);
    if (argc != 3) {
        fputs("usage: gen_eaw EastAsianWidth.txt UnicodeData.txt\n", stderr);
        return 2;
    }
    char *version = east_asian_width(argv[1]);
    unicode_data(argv[2]);
    qa_buf o = {};
    size_t nw = 0, nm = 0;
    qa_putf(&o, "/* Generated by tools/gen_eaw.c from the Unicode Character Database %s. Do not edit. */\n\n", version);
    emit(&o, "EAW_WF", wide, "Unicode East_Asian_Width Wide and Fullwidth", &nw);
    emit(&o, "COMB_MN", mark, "Unicode general category Mn (nonspacing) and Me (enclosing)", &nm);
    qa_write("src/eaw_tbl.inc", o.n, o.p);
    fprintf(stderr, "wrote src/eaw_tbl.inc (%zu W/F ranges, %zu Mn/Me ranges)\n", nw, nm);
}
